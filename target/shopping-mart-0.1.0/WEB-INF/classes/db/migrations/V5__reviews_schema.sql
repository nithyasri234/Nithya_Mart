CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL,

    product_id BIGINT NOT NULL,

    buyer_id BIGINT NOT NULL,

    rating INT NOT NULL,

    comment VARCHAR(1000),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reviews_order
        FOREIGN KEY (order_id)
        REFERENCES orders(id),

    CONSTRAINT fk_reviews_product
        FOREIGN KEY (product_id)
        REFERENCES products(id),

    CONSTRAINT fk_reviews_buyer
        FOREIGN KEY (buyer_id)
        REFERENCES users(id),

    CONSTRAINT chk_reviews_rating
        CHECK (rating BETWEEN 1 AND 5),

    CONSTRAINT uq_reviews_order_product_buyer
        UNIQUE (order_id, product_id, buyer_id)
);

CREATE INDEX idx_reviews_product_id
ON reviews(product_id);

CREATE INDEX idx_reviews_buyer_id
ON reviews(buyer_id);

CREATE INDEX idx_reviews_order_id
ON reviews(order_id);